export function getClubs(category = 'All') {
  if (!category || category === 'All') return CLUBS;
  return CLUBS.filter((club) => club.category === category);
}

export function getFeaturedClubs() {
  return CLUBS.filter((club) => club.featured);
}

export function getClubBySlug(slug) {
  return CLUBS.find((club) => club.slug === slug) || null;
}
